export const dict: Record<Lang, Record<string, string>> = { zh, en };

interface I18n {
  lang: Lang;
  t: (k: string) => string;
  tf: (k: string, vars: Record<string, string | number>) => string;
  setLang: (l: Lang) => void;
  toggle: () => void;
}

export const tr = (k: string, ph?: Record<string, string | number>) => {
  let out = dict[useI18n.getState().lang][k] ?? k;
  for (const [a, b] of Object.entries(ph ?? {})) out = out.split(`{${a}}`).join(String(b));
  return out;
};

export const useI18n = create<I18n>((set, get) => ({
  lang: (localStorage.getItem(KEY) as Lang) || 'zh',
  t: (k) => dict[get().lang][k] ?? k,
  tf: (k, vars) => {
    let out = dict[get().lang][k] ?? k;
    for (const [vk, vv] of Object.entries(vars)) out = out.replaceAll(`{${vk}}`, String(vv));
    return out;
  },
  setLang: (l) => {
    localStorage.setItem(KEY, l);
    set({ lang: l });
  },
  toggle: () => get().setLang(get().lang === 'zh' ? 'en' : 'zh'),
}));
